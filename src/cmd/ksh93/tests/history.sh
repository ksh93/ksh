# Tests for the shell history file, including locking and concurrent access.
. "${SHTESTS_COMMON:-${0%/*}/_common}"

((!SHOPT_SCRIPTONLY)) || { warning "interactive shell was compiled out -- tests skipped"; exit 0; }

# use maximum possible history size by default for these tests
HISTSIZE=16384

# ======
# Between 2025-05-30 and 2026-09-02, 'print -s' failed to write to the history file.
# https://github.com/ksh93/ksh/issues/1019
exp=hello$$
got=$(print -s "hello$$"; fc -l -0 2>&1)
[[ $got == *[$'\t ']"$exp" ]] || err_exit "print -s fails to write to history file" \
	"(expected match of *[\t ]$(printf %q "$exp"), got $(printf %q "$got"))"

# ======
# The tests until the next '# ======' were generated by Claude Opus 4.6 directed by Siteshwar
# Vashisht on 2026-09-02, then corrected and largely rewritten by Martijn Dekker.
# See https://github.com/ksh93/ksh/issues/997 and https://github.com/ksh93/ksh/pull/1020

# Basic sanity: a single interactive session writes and retains history
histfile=$tmp/hist_basic
got=$(
	HISTFILE=$histfile
	print -s "echo alpha"
	print -s "echo bravo"
	print -s "echo charlie"
	fc -l -N 3 2>&1
)
[[ $got == *alpha* && $got == *bravo* && $got == *charlie* ]] \
	|| err_exit "single session: print -s entries not retained in history (got $(printf %q "$got"))"
[[ -f $histfile ]] || err_exit "HISTFILE not created"

# History file survives re-open
histfile=$tmp/hist_reopen
HISTFILE=$histfile
print -s "first_session_cmd"
HISTFILE=/dev/null
got=$(HISTFILE=$histfile; fc -l -N 5 2>&1)
[[ $got == *first_session_cmd* ]] \
	|| err_exit "history entry from prior session not visible after reopen (got $(printf %q "$got"))"

# Concurrent writes to the same HISTFILE
# note: n_sessions * n_lines should be < 16384
histfile=$tmp/hist_concurrent
typeset -i n_sessions=64 n_lines=255 present total
typeset -Z3 s i
for ((s=0; s<n_sessions; s++))
do	(
		HISTFILE=$histfile
		typeset -Z3 i
		for ((i=0; i<$n_lines; i++))
		do	print -s "session_${s}_cmd_${i}"
		done
	) &
done
wait
# read back
((total = n_sessions * n_lines))
got=$(
	HISTFILE=$histfile
	fc -l -N "$((n_sessions * n_lines + 50))" 2>&1 | LC_ALL=C sed $'s/^[0-9]*[ \t]*//' | LC_ALL=C sort
)
present=$(print "$got" | wc -l)
if	((present == total))
then	exp=
	for ((s=0; s<n_sessions; s++))
	do	for ((i=0; i<n_lines; i++))
		do	exp+=${exp:+$'\n'}session_${s}_cmd_${i}
		done
	done
	test "$got" = "$exp" || err_exit "concurrent history writes: got $total entries as expected, but entries differ." \
		$'Diff follows:\n'"$(diff -u <(print -r -- "$exp") <(print -r -- "$got") | LC_ALL=C sed $'s/^/\t| /; 25s/.*/\t| [...]/; 26,$d')"
else	err_exit "concurrent history writes: expected $total entries, got $present." \
		$'Diff follows:\n'"$(diff -u <(print -r -- "$exp") <(print -r -- "$got") | LC_ALL=C sed $'s/^/\t| /; 25s/.*/\t| [...]/; 26,$d')"
fi
unset n_sessions n_lines s present total

# History trimming
typeset -i size1 size2
mkdir hist_trim
histfile=$tmp/hist_trim/sh_history
(
	HISTFILE=$histfile
	typeset -i i
	for ((i=0; i<1000; i++))
	do	print -s "trimtest_cmd_${i}"
	done
) >/dev/null 2>&1				# older ksh misdirects 'print -s' to stdout or stderr here
size1=$(wc -c <$histfile)
touch -t 202007120143.13 "$histfile"		# make the history file 'old' to force a physical trim of the file
chmod a-w hist_trim				# verify that trimming works with a non-writable parent directory
# only the last 50 entries should survive; 'print -s' triggers the trim
(
	HISTSIZE=50
	HISTFILE=$histfile
	print -s extra1001
) >/dev/null 2>&1				# older ksh misdirects 'print -s' to stdout or stderr here
chmod +w hist_trim				# avoid interfering with cleanup (rm -rf)
size2=$(wc -c <$histfile)
((size2 < size1)) || err_exit "history file did not reduce in size ($size2 >= $size1)"
grep -q trimtest_cmd_999 "$histfile" || err_exit "most recent entry lost after trim"
grep -q trimtest_cmd_0 "$histfile" && err_exit "oldest entry not trimmed"
grep -q trimtest_cmd_949 "$histfile" && err_exit "last old entry not trimmed"
grep -q trimtest_cmd_950 "$histfile" || err_exit "first kept entry trimmed"
grep -q extra1001 "$histfile" || err_exit "extra entry not added"
unset size1 size2

# Rapidly alternating sessions: open, write one entry, close; repeat
# with the same HISTFILE. Tests lock acquire/release cycling.
typeset -i s total=1000 present missing
histfile=$tmp/hist_cycle
exp=
for ((s=0; s<total; s++))
do	HISTFILE=$histfile
	print -s "cycle_cmd_$s"
	HISTFILE=/dev/null
done
HISTFILE=$histfile
got=$(fc -l -N "$((total + 15))" 2>&1 | LC_ALL=C sed $'s/^[0-9]*[ \t]*//')
present=$(print "$got" | wc -l)
if	((present == total))
then	exp=
	for ((s=0; s<total; s++))
	do	exp+=${exp:+$'\n'}cycle_cmd_$s
	done
	test "$got" = "$exp" || err_exit "sequential session cycling: got $total entries as expected, but entries differ." \
		$'Diff follows:\n'"$(diff -u <(print -r -- "$exp") <(print -r -- "$got") | LC_ALL=C sed $'s/^/\t| /; 25s/.*/\t| [...]/; 26,$d')"
else	err_exit "sequential session cycling: expected $total entries, got $present." \
		$'Diff follows:\n'"$(diff -u <(print -r -- "$exp") <(print -r -- "$got") | LC_ALL=C sed $'s/^/\t| /; 25s/.*/\t| [...]/; 26,$d')"
fi
unset s total present missing
HISTFILE=/dev/null

# Stress test 1: many concurrent sessions each writing one line, history file reinitialised for each line
histfile=$tmp/hist_stress_1
typeset -i total=200 present s
for ((s=0; s<total; s++))
do	(HISTFILE=$histfile; print -s "stress_cmd_$s") &
done
wait
got=$(HISTFILE=$histfile; fc -l -N 1 2>&1)
[[ e=$? -eq 0 && -n $got ]] || err_exit "ksh produced no history output after $total concurrent sessions" \
	"(got status $e, $(printf %q "$got")"
# verify history file's initial magic byte (HIST_UNDO == 8#201)
(LC_CTYPE=C; [[ $(<$histfile) == $'\201'* ]]) || err_exit "history file magic byte corrupted after stress test 1"
# read back
got=$(HISTFILE=$histfile; fc -l -N "$((total + 50))" 2>&1 | LC_ALL=C sed $'s/^[0-9]*[ \t]*//' | LC_ALL=C sort -n -t_ -k3)
present=$(print "$got" | wc -l)
if	((present == total))
then	exp=
	for ((s=0; s<total; s++))
	do	exp+=${exp:+$'\n'}stress_cmd_$s
	done
	test "$got" = "$exp" || err_exit "concurrent one-line stress test 1: got $total entries as expected, but entries differ." \
		$'Diff follows:\n'"$(diff -u <(print -r -- "$exp") <(print -r -- "$got") | LC_ALL=C sed $'s/^/\t| /; 25s/.*/\t| [...]/; 26,$d')"
else
	err_exit "concurrent one-line stress test 1: expected $total entries, got $present." \
		$'Diff follows:\n'"$(diff -u <(print -r -- "$exp") <(print -r -- "$got") | LC_ALL=C sed $'s/^/\t| /; 25s/.*/\t| [...]/; 26,$d')"
fi
unset total present s histfile

# Stress test 2: many concurrent sessions each writing one line, history file initialised once
HISTFILE=$tmp/hist_stress_2
typeset -i total=200 present s
for ((s=0; s<total; s++))
do	print -s "stress_cmd_$s" &
done
wait
got=$(fc -l -N 1 2>&1)
[[ e=$? -eq 0 && -n $got ]] || err_exit "ksh produced no history output after $total concurrent sessions" \
	"(got status $e, $(printf %q "$got")"
# verify history file's initial magic byte (HIST_UNDO == 8#201)
(LC_CTYPE=C; [[ $(<$HISTFILE) == $'\201'* ]]) || err_exit "history file magic byte corrupted after stress test 2"
# read back
got=$(fc -l -N "$((total + 50))" 2>&1 | LC_ALL=C sed $'s/^[0-9]*[ \t]*//' | LC_ALL=C sort -n -t_ -k3)
present=$(print "$got" | wc -l)
if	((present == total))
then	exp=
	for ((s=0; s<total; s++))
	do	exp+=${exp:+$'\n'}stress_cmd_$s
	done
	test "$got" = "$exp" || err_exit "concurrent one-line stress test 2: got $total entries as expected, but entries differ." \
		$'Diff follows:\n'"$(diff -u <(print -r -- "$exp") <(print -r -- "$got") | LC_ALL=C sed $'s/^/\t| /; 25s/.*/\t| [...]/; 26,$d')"
else
	err_exit "concurrent one-line stress test 2: expected $total entries, got $present." \
		$'Diff follows:\n'"$(diff -u <(print -r -- "$exp") <(print -r -- "$got") | LC_ALL=C sed $'s/^/\t| /; 25s/.*/\t| [...]/; 26,$d')"
fi
unset total present s
HISTFILE=/dev/null

# A command that is entered over multiple lines must not be written to the
# history file before it is complete: a command that another session writes in
# the meantime would end up in the middle of it, leaving an unterminated
# command behind that is cancelled or merged on the next scan, so both commands
# are lost. The complete command must be stored as one unit. The history index
# of the session that entered it must also include the commands written by
# other sessions, or that session cannot find its own command with fc or by
# scrolling back with the arrow keys.
# https://github.com/ksh93/ksh/issues/864
typeset -i i
long=$(awk -v ORS= 'BEGIN { for (i = 0; i < 4200; i++) print "x"; }')
for variant in small large
do	histfile=$tmp/hist_multiline/$variant/history
	mkdir -p "${histfile%/*}" || exit
	: >$histfile
	fifo=$histfile.fifo
	mkfifo -m 600 "$fifo" || { warning "mkfifo failed; skipping concurrent multiline commands test"; break; }
	HISTFILE=$histfile "$SHELL" -i <$fifo >$histfile.out 2>&1 &
	hpid=$!
	exec 9>$fifo		# keep the fifo open: the shell must not see EOF yet
	# Wait until the session has started and written to its history file.
	print -u9 "print WARMUP"
	for ((i = 0; i < 100; i++))
	do	grep -q WARMUP "$histfile" && break
		sleep .01
	done
	if	[[ $variant == large ]]
	then	marker="LONGDONE # $long"			# larger than HIST_BSIZE
		print -u9 "if true; then print $marker"
		# Only a command larger than HIST_BSIZE was wrongly written to the
		# file before it was finished; wait for that first so that the
		# corruption is reproduced, otherwise this loop just expires.
		size=$(wc -c <$histfile)
		for ((i = 0; i < 100; i++))
		do	(( $(wc -c <$histfile) > size )) && break
			sleep .01
		done
	else	marker="then print SMALLDONE"			# well within HIST_BSIZE
		print -u9 "if true"
		print -u9 "$marker"
	fi
	(HISTFILE=$histfile; print -s other_session)		# concurrent write
	print -u9 fi
	print -u9 'fc -ln 1'
	print -u9 exit
	exec 9>&-
	wait "$hpid"
	# The session that entered the command must have both in its own history.
	got=$(<$histfile.out)
	[[ $got == *other_session* ]] \
		|| err_exit "multiline history command ($variant): concurrent session's command lost" \
		"(fc output: $(printf %q "$got"))"
	[[ $got == *"$marker"* ]] || err_exit "multiline history command ($variant):" \
		"incomplete or lost after a concurrent write" \
		"(fc output: $(printf %q "$got" | cut -c 1-200))"
	# A new session must find both commands in the history file as well.
	got=$(
		HISTFILE=$histfile
		fc -ln 1 2>&1
	)
	[[ $got == *other_session* ]] || err_exit "multiline history command ($variant):" \
		"concurrent session's command not in history file" \
		"(fc output: $(printf %q "$got"))"
	[[ $got == *"$marker"* ]] || err_exit "multiline history command ($variant):" \
		"missing from history file" \
		"(fc output: $(printf %q "$got"))"
done
unset i long variant histfile fifo hpid got marker size

